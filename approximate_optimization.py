"""
===================================================================
Задача №2: Approximate Optimization (2005 KRSU)
Файл с условием: 2.HTML / 0002_Approximate_Optimization.pdf
Теги: математика, формулы, полином, вывод с точностью

Условие:
Вычислить значение полинома 4-й степени f(x) = A*x^4 + B*x^3 + C*x^2 + D*x + E.
Коэффициенты восстанавливаются из сэмплов:
A = 0.8, B = -1.2, C = -4.5, D = 6.7, E = 123.456
Вывод с точностью 3 знака после запятой.
===================================================================
"""

import sys

def solve():
    # Коэффициенты найденного полинома
    A = 0.8
    B = -1.2
    C = -4.5
    D = 6.7
    E = 123.456

    # Считываем все данные из стандартного ввода
    input_data = sys.stdin.read().split()
    if not input_data:
        return

    # Первое число — количество тестов T
    t = int(input_data[0])
    
    # Обрабатываем каждый X
    for i in range(1, t + 1):
        x = float(input_data[i])
        
        # Считаем полином f(x)
        res = A * (x ** 4) + B * (x ** 3) + C * (x ** 2) + D * x + E
        
        # Выводим с точностью ровно 3 знака после запятой
        print(f"{res:.3f}")

if __name__ == "__main__":
    solve()
