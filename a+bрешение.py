import sys

def main():
    # Считываем всю строку из стандартного ввода,
    # разбиваем по пробелам и превращаем в числа
    try:
        data = sys.stdin.read().split()
        if not data:
            return
        
        a = int(data[0])
        b = int(data[1])
        
        # Выводим результат
        print(a + b)
    except Exception:
        # Если ввод берется через обычный input():
        # a, b = map(int, input().split())
        # print(a + b)
        pass

if __name__ == "__main__":
    main()
